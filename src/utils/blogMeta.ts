/** The post's category label and topic, for posts that have a banner. */
export function blogCategory(slug: string): { label: string; topic: BlogTopic } | undefined {
  const m = POSTS[slug];
  return m ? { label: m[0], topic: m[1] } : undefined;
}

/** The post's banner (1600x900), or undefined for a post added after the banner set was made. */
export function blogCover(slug: string): string | undefined {
  return POSTS[slug] ? `/images/blog/covers/${slug}.webp` : undefined;
}

/** Reading time in minutes, from the post's HTML (about 220 words a minute). */
export function readMinutes(html: string): number {
  return Math.max(2, Math.round(html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length / 220));
}

/** Plain-text excerpt of the post's HTML, for posts without a description. */
export function excerpt(html: string, max = 170): string {
  const text = html.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
  return text.length > max ? text.slice(0, text.lastIndexOf(" ", max)) + "…" : text;
}
